package commons;

/**
 * Represents a set of unit types that could be used in a recipe via RecipeIngredients
 */
public enum Unit {
    /**
     * kilograms
     */
    kg,

    /**
     * grams
     */
    g,
    /**
     * Litres
     */
    L,

    /**
     * millilitres
     */
    mL,

    /**
     * tablespoons
     */
    tbsp,

    /**
     * teaspoons
     */
    tsp,

    /**
     * pinch (informal)
     */
    pinch
}
